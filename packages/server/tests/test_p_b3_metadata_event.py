"""B3 — quality-disclosure SSE metadata event on provider fallback.

When primary fails mid-stream and a different (often cheaper / weaker)
model takes over, the user sees the response style change mid-message
without explanation. Common user reaction: "the AI broke / the book is
bad / my prompt was wrong" — when the real cause is a silent provider
downgrade.

The metadata event gives clients a hook to surface "AI response
generated by fallback model — quality may be reduced" so users attribute
the change correctly.

These tests pin:
- Event schema (type/request_id/model/fallback_used/primary_model)
- JSON-validity (clients must be able to parse it)
- Emission BEFORE fallback content chunks (so client UI knows upfront)
- No emission when no fallback is available
"""

from __future__ import annotations

import json

import pytest

from app.services.companion.stream_cache import sse_metadata_event


def test_sse_metadata_event_basic_schema():
    """Event carries the 4 mandatory fields in the documented shape."""
    chunk = sse_metadata_event(
        request_id='req-abc',
        model='deepseek-chat',
        fallback_used=True,
        primary_model='glm-4.7-flash',
        primary_provider='glm',
    )
    assert chunk.startswith('data: ')
    assert chunk.endswith('\n\n')
    payload = json.loads(chunk[len('data: '):-2])
    assert payload['type'] == 'metadata'
    assert payload['request_id'] == 'req-abc'
    assert payload['model'] == 'deepseek-chat'
    assert payload['fallback_used'] is True
    assert payload['primary_model'] == 'glm-4.7-flash'
    assert payload['primary_provider'] == 'glm'


def test_sse_metadata_event_omits_optional_fields_when_none():
    """primary_model / primary_provider are optional — clients should be
    able to handle their absence (e.g. if a future caller doesn't know
    the failed model)."""
    chunk = sse_metadata_event(
        request_id='req-xyz',
        model='glm-4.7-flash',
        fallback_used=False,
    )
    payload = json.loads(chunk[len('data: '):-2])
    assert 'primary_model' not in payload
    assert 'primary_provider' not in payload
    assert payload['fallback_used'] is False


def test_sse_metadata_event_special_chars_in_model_name():
    """Model names can contain dots, dashes, slashes — JSON encoder must
    handle them without breaking the SSE frame."""
    chunk = sse_metadata_event(
        request_id='req-special',
        model='gpt-4.1-nano-2025-04-14',
        fallback_used=True,
        primary_model='glm-4.7-flash',
    )
    # The frame is exactly one 'data:' line + \n\n. No embedded \n leaks.
    assert chunk.count('\n') == 2
    payload = json.loads(chunk[len('data: '):-2])
    assert payload['model'] == 'gpt-4.1-nano-2025-04-14'


def test_sse_metadata_event_is_json_parseable_by_client_parser():
    """A standard SSE parser splits on '\\n\\n' and JSON-parses the data
    payload. The chunk must round-trip cleanly through that pipeline."""
    chunk = sse_metadata_event(
        request_id='req-parse',
        model='m',
        fallback_used=True,
        primary_model='p',
    )
    # Strip the 'data: ' prefix and trailing \n\n, parse the body.
    body = chunk[6:-2]
    parsed = json.loads(body)
    assert parsed['type'] == 'metadata'


